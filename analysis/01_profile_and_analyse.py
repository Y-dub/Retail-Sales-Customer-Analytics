"""Online Retail: data-quality profiling, cleaning, KPIs and RFM segmentation.

Writes docs/findings.md (the evidence base for the BRD, RTM and dashboard) and the derived
datasets in data/. Run from anywhere: python analysis/01_profile_and_analyse.py
"""

from __future__ import annotations

import pandas as pd
from cleaning import ROOT, classify, data_quality_checks, load_raw

DATA, DOCS = ROOT / "data", ROOT / "docs"
lines: list[str] = []


def log(s: str = "") -> None:
    lines.append(s)
    print(s)


def gbp(x: float) -> str:
    return f"£{x:,.0f}"


raw = load_raw()
df = classify(raw)
n_raw = len(df)

sales = df[df["line_type"] == "product_sale"]
returns = df[df["line_type"] == "product_return"]
product = df[df["is_product_line"]]

log("# Retail Sales & Customer Analytics: current-state findings")
log(f"\n_Dataset: UCI Online Retail (UK online giftware retailer). Raw rows: {n_raw:,}. "
    f"Period: {df['InvoiceDate'].min():%d %b %Y} to {df['InvoiceDate'].max():%d %b %Y}._")
log("\n_Generated by `analysis/01_profile_and_analyse.py`; do not edit by hand._")

# ---------- 1. Data quality ----------
log("\n## 1. Data-quality checks\n")
log("Independent checks on the raw rows; one row can fail more than one.\n")
log("| Check | Rows | % of raw | Action |")
log("|---|---|---|---|")
for r in data_quality_checks(raw).itertuples():
    log(f"| {r.check} | {r.rows:,} | {r.pct_of_raw:.1f}% | {r.action} |")

unattributed = sales.loc[sales["CustomerID"].isna(), "Revenue"].sum() / sales["Revenue"].sum()
log(f"\nRows without a CustomerID account for **{unattributed:.1%} of gross product sales**, "
    f"so customer-level results (RFM) describe the remaining {1 - unattributed:.1%}.")

# ---------- 2. Classification ----------
log("\n## 2. How every row is classified\n")
log("Rules are applied in order; each row gets exactly one type (see `analysis/cleaning.py`).\n")
order = ["product_sale", "product_return", "non_product", "order_error", "price_error",
         "duplicate", "stock_adjustment", "invalid_price"]
summary = df.groupby("line_type").agg(rows=("Revenue", "size"), value=("Revenue", "sum")).reindex(order).fillna(0)
log("| Line type | Rows | % of raw | Value |")
log("|---|---|---|---|")
for t, r in summary.iterrows():
    log(f"| {t} | {int(r.rows):,} | {r.rows / n_raw:.1%} | {gbp(r.value)} |")

errors = df[df["line_type"] == "order_error"]
err_sales = errors[~errors["is_cancellation"]]
log(f"\n**Order errors:** {len(err_sales)} sale lines worth {gbp(err_sales['Revenue'].sum())} were reversed "
    "in full within 24 hours (same customer, product and quantity). They are excluded from both sales "
    "and returns:\n")
for r in err_sales.itertuples():
    log(f"- {r.Description.strip()}: {r.Quantity:,} units, {gbp(r.Revenue)} "
        f"(customer {int(r.CustomerID)}, {r.InvoiceDate:%d %b %Y})")

price_err = df[df["line_type"] == "price_error"]
log(f"\n**Price errors:** {len(price_err)} sale lines priced over 50x the product's median "
    f"({gbp(price_err['Revenue'].sum())}), e.g. {price_err['Description'].iloc[0].strip()} at "
    f"£{price_err['UnitPrice'].iloc[0]:,.2f}. Excluded." if len(price_err) else "")

np_lines = df[df["line_type"] == "non_product"]
log("\n**Non-product lines** (excluded from product metrics):\n")
log("| Category | Rows | Net value |")
log("|---|---|---|")
for cat, r in np_lines.groupby("non_product_category")["Revenue"].agg(["size", "sum"]).sort_values("sum").iterrows():
    log(f"| {cat} | {int(r['size']):,} | {gbp(r['sum'])} |")

# ---------- 3. KPIs ----------
log("\n## 3. Headline KPIs (product lines only)\n")
gross, ret = sales["Revenue"].sum(), returns["Revenue"].sum()
net = gross + ret
orders = sales["InvoiceNo"].nunique()
kpis = {
    "Gross product sales": gbp(gross),
    "Product returns": gbp(ret),
    "Net product revenue": gbp(net),
    "Return rate (returns / gross sales)": f"{-ret / gross:.1%}",
    "Orders (distinct sale invoices)": f"{orders:,}",
    "Average order value (gross sales / orders)": f"£{gross / orders:,.2f}",
    "Customers with an ID": f"{sales['CustomerID'].nunique():,}",
    "Distinct products sold": f"{sales['StockCode'].nunique():,}",
}
for k, v in kpis.items():
    log(f"- **{k}:** {v}")

# ---------- 4. Monthly ----------
log("\n## 4. Revenue by month\n")
by_month = product.groupby(["InvoiceMonth", "line_type"])["Revenue"].sum().unstack(fill_value=0)
by_month = by_month.rename(columns={"product_sale": "GrossSales", "product_return": "Returns"})
by_month["NetRevenue"] = by_month["GrossSales"] + by_month["Returns"]
log("| Month | Gross sales | Returns | Net revenue |")
log("|---|---|---|---|")
for m, r in by_month.iterrows():
    log(f"| {m} | {gbp(r.GrossSales)} | {gbp(r.Returns)} | {gbp(r.NetRevenue)} |")
log("\n_December 2011 covers 1–9 December only._")

# ---------- 5. Markets and products ----------
log("\n## 5. Markets and products (net product revenue)\n")
by_country = product.groupby("Country")["Revenue"].sum().sort_values(ascending=False)
log("| Country | Net revenue | Share |")
log("|---|---|---|")
for c, v in by_country.head(6).items():
    log(f"| {c} | {gbp(v)} | {v / net:.1%} |")
top = product.groupby("Description")["Revenue"].sum().sort_values(ascending=False).head(8)
log("\n| Product | Net revenue |")
log("|---|---|")
for p, v in top.items():
    log(f"| {p.strip()} | {gbp(v)} |")

# ---------- 6. RFM ----------
log("\n## 6. RFM customer segmentation\n")
cust_lines = product.dropna(subset=["CustomerID"])
snapshot = cust_lines["InvoiceDate"].max() + pd.Timedelta(days=1)
cust_sales = cust_lines[cust_lines["line_type"] == "product_sale"]
rfm = pd.DataFrame({
    "Recency": (snapshot - cust_sales.groupby("CustomerID")["InvoiceDate"].max()).dt.days,
    "Frequency": cust_sales.groupby("CustomerID")["InvoiceNo"].nunique(),
    "Monetary": cust_lines.groupby("CustomerID")["Revenue"].sum(),  # net of returns
}).dropna()
excluded = int((rfm["Monetary"] <= 0).sum())
rfm = rfm[rfm["Monetary"] > 0]
rfm["R"] = pd.qcut(rfm["Recency"], 4, labels=[4, 3, 2, 1]).astype(int)
rfm["F"] = pd.qcut(rfm["Frequency"].rank(method="first"), 4, labels=[1, 2, 3, 4]).astype(int)
rfm["M"] = pd.qcut(rfm["Monetary"], 4, labels=[1, 2, 3, 4]).astype(int)
rfm["RFM"] = rfm[["R", "F", "M"]].sum(axis=1)


def segment(r: pd.Series) -> str:
    if r.R >= 3 and r.F >= 3 and r.M >= 3:
        return "Champions"
    if r.R >= 3 and r.F >= 2:
        return "Loyal"
    if r.R >= 3:
        return "Recent / promising"
    if r.R == 2:
        return "At risk"
    return "Lost / dormant"


rfm["Segment"] = rfm.apply(segment, axis=1)
log("Monetary = net product spend (sales minus returns). Recency and frequency use sale invoices only. "
    f"{excluded} customers with zero or negative net spend (returns of pre-period purchases) are excluded.\n")
seg = rfm.groupby("Segment")["Monetary"].agg(Customers="size", Avg="mean", Total="sum").sort_values(
    "Total", ascending=False)
log("| Segment | Customers | % of customers | Avg net spend | % of net revenue |")
log("|---|---|---|---|---|")
for s, r in seg.iterrows():
    log(f"| {s} | {int(r.Customers):,} | {r.Customers / len(rfm):.0%} | {gbp(r.Avg)} | "
        f"{r.Total / rfm['Monetary'].sum():.0%} |")

# ---------- save ----------
df.to_csv(DATA / "classified_lines.csv", index=False)
rfm.reset_index().to_csv(DATA / "rfm_segments.csv", index=False)
by_month[["GrossSales", "Returns", "NetRevenue"]].round(2).to_csv(DATA / "revenue_by_month.csv")
(DOCS / "findings.md").write_text("\n".join(lines) + "\n")
print("\n[saved] data/classified_lines.csv, data/rfm_segments.csv, data/revenue_by_month.csv, docs/findings.md")
